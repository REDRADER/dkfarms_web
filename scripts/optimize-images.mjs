// Prepares the resort's photos for the site.
//
//   1. Put original photos (JPG/PNG/WebP/HEIC exported as JPG) in `photos/`.
//      The file name becomes the image key used in content/*.json,
//      e.g. photos/pool-villa.jpg -> "image": "pool-villa".
//   2. Run `pnpm images`.
//
// Each photo is rotated upright, capped at 2400px on the long side, converted
// to sRGB, stripped of EXIF/GPS data and saved as a high-quality JPEG in
// `assets/photos/`. next/image then serves AVIF/WebP at the right size for each
// screen. Finally `content/images.generated.ts` is rewritten so every photo is a
// static import (that gives width/height and blur placeholders for free).

import { readdir, mkdir, writeFile, stat } from "node:fs/promises";
import path from "node:path";

let sharp;
try {
  sharp = (await import("sharp")).default;
} catch {
  console.error('"sharp" isn\'t installed. Run `pnpm install` (it\'s a devDependency), then `pnpm images` again.');
  process.exit(1);
}

const root = path.resolve(import.meta.dirname, "..");
const srcDir = path.join(root, "photos");
const outDir = path.join(root, "assets", "photos");
const registry = path.join(root, "content", "images.generated.ts");

const MAX_EDGE = 2400;
const BUDGET_KB = 600; // warn if an optimised original is still heavier than this
const exts = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif", ".tif", ".tiff"]);

const toKey = (file) =>
  path
    .basename(file, path.extname(file))
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

await mkdir(outDir, { recursive: true });

let sources = [];
try {
  sources = (await readdir(srcDir)).filter((f) => exts.has(path.extname(f).toLowerCase()));
} catch {
  console.log("No photos/ folder found, only rebuilding the registry.");
}

for (const file of sources) {
  const key = toKey(file);
  const out = path.join(outDir, `${key}.jpg`);
  await sharp(path.join(srcDir, file))
    .rotate()
    .resize({ width: MAX_EDGE, height: MAX_EDGE, fit: "inside", withoutEnlargement: true })
    .toColorspace("srgb")
    .jpeg({ quality: 82, mozjpeg: true, progressive: true })
    .toFile(out);
  const kb = Math.round((await stat(out)).size / 1024);
  console.log(`${kb > BUDGET_KB ? "!" : "✓"} ${file} -> assets/photos/${key}.jpg (${kb} KB)`);
}

const keys = (await readdir(outDir))
  .filter((f) => f.endsWith(".jpg"))
  .map((f) => f.slice(0, -4))
  .sort();

const ident = (k) => "img_" + k.replace(/-/g, "_");
const lines = [
  "// Generated by scripts/optimize-images.mjs. Do not edit by hand: run `pnpm images`.",
  'import type { StaticImageData } from "next/image";',
  ...keys.map((k) => `import ${ident(k)} from "@/assets/photos/${k}.jpg";`),
  "",
  "export const images: Record<string, StaticImageData> = {",
  ...keys.map((k) => `  "${k}": ${ident(k)},`),
  "};",
  "",
];
await writeFile(registry, lines.join("\n"));
console.log(`Registry updated with ${keys.length} images.`);
